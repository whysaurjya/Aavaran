    getCurrentLang: function () {
        var saved = localStorage.getItem('aavaran_lang') || localStorage.getItem('prahari_lang') || 'en';
        return this.languages[saved] ? saved : 'en';
    },

    setLang: function (langCode) {
        if (!this.languages[langCode]) langCode = 'en';
        localStorage.setItem('aavaran_lang', langCode);
        localStorage.setItem('prahari_lang', langCode);
        this.applyTranslations(langCode);
        this.updateLangBadge(langCode);
    },

    updateLangBadge: function (langCode) {
        var lang = this.languages[langCode];
        var badge = document.getElementById('current-lang-badge');
        var display = document.getElementById('current-lang-display');
        if (badge) badge.textContent = lang.code;
        if (display) display.textContent = lang.name + (langCode === 'en' ? ' (Default)' : ' (' + lang.code + ')');

        document.querySelectorAll('.language-option-card').forEach(function (card) {
            if (card.getAttribute('data-lang') === langCode) {
                card.classList.add('active');
                var radio = card.querySelector('input[type="radio"]');
                if (radio) radio.checked = true;
            } else {
                card.classList.remove('active');
            }
        });
    },

    applyTranslations: function (langCode) {
        var t = this.translations[langCode] || this.translations.en;
        var defaultT = this.translations.en;

        function get(key) {
            return t[key] || defaultT[key] || '';
        }

        // Common text selectors
        var textMap = [
            { sel: '.hero-eyebrow-badge span:nth-child(2)', key: 'hero_eyebrow' },
            { sel: '.hero-btn-primary span', key: 'hero_btn_scan' },
            { sel: '.hero-btn-secondary span', key: 'hero_btn_predict' },
            { sel: '.score-card-title', key: 'score_title' },
            { sel: '.score-status-pill .status-text', key: 'score_status' },
            { sel: '.score-supporting-text', key: 'score_desc' },
            { sel: '.risk-col:nth-child(1) .risk-label', key: 'risk_weather' },
            { sel: '.risk-col:nth-child(2) .risk-label', key: 'risk_infra' },
            { sel: '.risk-col:nth-child(3) .risk-label', key: 'risk_safety' },
            { sel: '.footer-copyright-text p', key: 'copyright_belt' }
        ];

        textMap.forEach(function (item) {
            var el = document.querySelector(item.sel);
            if (el) {
                var text = get(item.key);
                if (text) el.textContent = text;
            }
        });
    },

    init: function () {
        var self = this;
        var currentLang = this.getCurrentLang();
        this.updateLangBadge(currentLang);

        // Modal triggers
        var openBtn = document.getElementById('open-language-modal-btn');
        var modal = document.getElementById('language-modal');
        var closeBtn = document.getElementById('language-modal-close');
        var backdrop = document.getElementById('language-modal-backdrop');
        var applyBtn = document.getElementById('apply-language-btn');

        function openModal() {
            if (modal) {
                modal.classList.add('active');
                document.body.style.overflow = 'hidden';
            }
        }

        function closeModal() {
            if (modal) {
                modal.classList.remove('active');
                document.body.style.overflow = '';
            }
        }

        if (openBtn) openBtn.addEventListener('click', openModal);
        if (closeBtn) closeBtn.addEventListener('click', closeModal);
        if (backdrop) backdrop.addEventListener('click', closeModal);

        document.querySelectorAll('.language-option-card').forEach(function (card) {
            card.addEventListener('click', function () {
                document.querySelectorAll('.language-option-card').forEach(function (c) { c.classList.remove('active'); });
                card.classList.add('active');
                var radio = card.querySelector('input[type="radio"]');
                if (radio) radio.checked = true;
            });
        });

        if (applyBtn) {
            applyBtn.addEventListener('click', function () {
                var selected = document.querySelector('.language-option-card.active');
                if (selected) {
                    var lang = selected.getAttribute('data-lang');
                    self.setLang(lang);
                }
                closeModal();
            });
        }
    }
